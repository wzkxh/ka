#!/usr/bin/env python3
"""Dev tool: assemble tools/float_rt.asm, tools/time_rt.asm and tools/int_rt.asm and put the machine code into kota.py between the BEGIN/END FLOAT_RT, TIME_RT and INT_RT markers.
Needs `pip install keystone-engine`; NOT needed to use the compiler (kota.py already contains the bytes).
Keystone assembles the single instructions; jumps and labels are handled here (every jump is a rel32)."""
import os, re, struct, sys
import keystone

JCC = {"je": 4, "jz": 4, "jne": 5, "jnz": 5, "jl": 0xC, "jge": 0xD, "jle": 0xE, "jg": 0xF, "js": 8, "jns": 9,
       "jp": 0xA, "jnp": 0xB, "ja": 7, "jae": 3, "jb": 2, "jbe": 6, "jo": 0, "jno": 1}
ks = keystone.Ks(keystone.KS_ARCH_X86, keystone.KS_MODE_64)
cache = {}


def one(text):
  if text not in cache:
    code, _ = ks.asm(text)
    cache[text] = bytes(code)
  return cache[text]


def assemble(body):
  items, labels, pos = [], {}, 0       # items: ("raw", bytes) | ("jump", opcode bytes, label)
  for raw in body.split("\n"):
    line = raw.split(";")[0].strip()
    if not line:
      continue
    if line.endswith(":"):
      labels[line[:-1]] = pos
      continue
    op, _, rest = line.partition(" ")
    if op == "db":                                  # raw bytes: db 0x4D, 0x6F
      b = bytes(int(x, 0) for x in rest.split(","))
      items.append(("raw", b)); pos += len(b)
    elif re.fullmatch(r"lea rax,\s*\[rip\s*\+\s*(\w+)\]", line):   # lea rax,[rip + label]: the address of a label of this routine
      items.append(("lea", b"\x48\x8D\x05", re.fullmatch(r"lea rax,\s*\[rip\s*\+\s*(\w+)\]", line).group(1))); pos += 7
    elif op == "jmp":
      items.append(("jump", b"\xE9", rest.strip())); pos += 5
    elif op in JCC:
      items.append(("jump", bytes([0x0F, 0x80 + JCC[op]]), rest.strip())); pos += 6
    else:
      b = one(line)
      items.append(("raw", b)); pos += len(b)
  out, pos = bytearray(), 0
  for it in items:
    if it[0] == "raw":
      out += it[1]; pos += len(it[1])
    else:                                           # jump or lea with a 32-bit displacement
      size = len(it[1]) + 4
      out += it[1] + struct.pack("<i", labels[it[2]] - (pos + size)); pos += size
  return bytes(out)


def build(asm_file):
  src = open(os.path.join(os.path.dirname(os.path.abspath(__file__)), asm_file)).read()
  parts = re.split(r"^;;; (rt_\w+)\n", src, flags=re.M)
  return {name: assemble(body) for name, body in zip(parts[1::2], parts[2::2])}


def render(blobs, name, asm_file):
  lines = [f"# ---- BEGIN {name} (generated by tools/build_float_rt.py from tools/{asm_file}; do not edit by hand)",
           f"{name} = {{"]
  for rname, b in blobs.items():
    h = b.hex()
    lines.append(f'  "{rname}": bytes.fromhex(')
    lines += [f'    "{h[i:i + 100]}"' for i in range(0, len(h), 100)]
    lines.append("  ),")
  lines += ["}", f"# ---- END {name}"]
  return "\n".join(lines)


FILES = (("FLOAT_RT", "float_rt.asm"), ("TIME_RT", "time_rt.asm"), ("INT_RT", "int_rt.asm"))

if __name__ == "__main__":
  path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "kota.py")
  text = open(path).read()
  for name, asm_file in FILES:
    blobs = build(asm_file)
    if "--print" in sys.argv:
      print(render(blobs, name, asm_file)); continue
    if f"# ---- BEGIN {name}" not in text:
      raise SystemExit(f"markers {name} not found in kota.py")
    text = re.sub(rf"# ---- BEGIN {name}.*?# ---- END {name}", lambda m: render(blobs, name, asm_file), text, flags=re.S)
    print(name, {k: len(v) for k, v in blobs.items()}, "bytes")
  if "--print" not in sys.argv:
    open(path, "w").write(text)
