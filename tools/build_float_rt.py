#!/usr/bin/env python3
"""Dev tool: assemble tools/float_rt.asm and put the machine code into ka.py between the BEGIN/END FLOAT_RT markers.
Needs `pip install keystone-engine`; NOT needed to use the compiler (ka.py already contains the bytes).
Keystone assembles the single instructions; jumps and labels are handled here (every jump is a rel32)."""
import os, re, struct, sys
import keystone

JCC = {"je": 4, "jz": 4, "jne": 5, "jnz": 5, "jl": 0xC, "jge": 0xD, "jle": 0xE, "jg": 0xF, "js": 8, "jns": 9,
       "jp": 0xA, "jnp": 0xB, "ja": 7, "jae": 3, "jb": 2, "jbe": 6}
ks = keystone.Ks(keystone.KS_ARCH_X86, keystone.KS_MODE_64)
cache = {}


def one(text):
  if text not in cache:
    code, _ = ks.asm(text)
    cache[text] = bytes(code)
  return cache[text]


def assemble(body):
  items, labels, pos = [], {}, 0       # items: ("raw", bytes) | ("jump", opcode bytes, label)
  for raw in body.split("\n"):
    line = raw.split(";")[0].strip()
    if not line:
      continue
    if line.endswith(":"):
      labels[line[:-1]] = pos
      continue
    op, _, rest = line.partition(" ")
    if op == "jmp":
      items.append(("jump", b"\xE9", rest.strip())); pos += 5
    elif op in JCC:
      items.append(("jump", bytes([0x0F, 0x80 + JCC[op]]), rest.strip())); pos += 6
    else:
      b = one(line)
      items.append(("raw", b)); pos += len(b)
  out, pos = bytearray(), 0
  for it in items:
    if it[0] == "raw":
      out += it[1]; pos += len(it[1])
    else:
      size = len(it[1]) + 4
      out += it[1] + struct.pack("<i", labels[it[2]] - (pos + size)); pos += size
  return bytes(out)


def build():
  src = open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "float_rt.asm")).read()
  parts = re.split(r"^;;; (rt_\w+)\n", src, flags=re.M)
  return {name: assemble(body) for name, body in zip(parts[1::2], parts[2::2])}


def render(blobs):
  lines = ["# ---- BEGIN FLOAT_RT (generated by tools/build_float_rt.py from tools/float_rt.asm; do not edit by hand)",
           "FLOAT_RT = {"]
  for name, b in blobs.items():
    h = b.hex()
    lines.append(f'  "{name}": bytes.fromhex(')
    lines += [f'    "{h[i:i + 100]}"' for i in range(0, len(h), 100)]
    lines.append("  ),")
  lines += ["}", "# ---- END FLOAT_RT"]
  return "\n".join(lines)


if __name__ == "__main__":
  blobs = build()
  if "--print" in sys.argv:
    print(render(blobs)); sys.exit()
  path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "ka.py")
  text = open(path).read()
  if "# ---- BEGIN FLOAT_RT" not in text:
    raise SystemExit("markers not found in ka.py")
  text = re.sub(r"# ---- BEGIN FLOAT_RT.*?# ---- END FLOAT_RT", lambda m: render(blobs), text, flags=re.S)
  open(path, "w").write(text)
  print({k: len(v) for k, v in blobs.items()}, "bytes written to ka.py")
