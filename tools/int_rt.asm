  mov eax, dword ptr [rsi]
  cmp eax, 0x61
  jb text_store
  mov r9, r8
scan:
  mov edx, dword ptr [r9]
  test edx, edx
  jz text_store
  cmp eax, edx
  jb scan_next
  cmp eax, dword ptr [r9 + 4]
  ja scan_next
  mov r10d, eax
  sub r10d, edx
  mov r11d, dword ptr [r9 + 12]
  dec r11d
  test r10d, r11d
  jnz scan_next
  add eax, dword ptr [r9 + 8]
  jmp text_store
scan_next:
  add r9, 16
  jmp scan
text_store:
  mov dword ptr [rdi], eax
  add rsi, 4
  add rdi, 4
  dec rcx
  jnz text_next
text_done:
  ret
