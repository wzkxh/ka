;;; Same rules as float_rt.asm: position independent, self-contained (no calls, no imports), every register except rbp and rsp may be changed.
;;;
;;; rt_isprime   in: rax = n (int)   out: rax = 1 if n is prime, else 0   (the unary operator *n)
;;;   n < 66: a table of 64 bits, bit (n - 2) is set for the primes 2..65 (0x0A08228828228A2B), n < 2 gives 0.
;;;   else: even numbers and multiples of 3 are not prime; then trial division by i and i + 2 for i = 5, 11, 17, ... while i * i <= n.
;;;   i * i is checked for signed overflow: for n near the top of the int range the square of the first i beyond the root does not fit,
;;;   and without the check the loop would go on for billions of steps (the product wraps to a negative number).
;;; rt_isprime
  cmp rax, 66
  jge big
  cmp rax, 2
  jl not_prime
  lea rcx, [rax - 2]
  mov rdx, 0x0A08228828228A2B
  shr rdx, cl
  mov eax, edx
  and eax, 1
  ret
big:
  test al, 1
  jz not_prime
  mov r8, rax                    ; n
  xor edx, edx
  mov ecx, 3
  div rcx
  test rdx, rdx
  jz not_prime
  mov r9d, 5                     ; i
next_i:
  mov rax, r9
  imul rax, r9                   ; i * i
  jo is_prime                    ; does not fit: i * i > n for sure
  cmp rax, r8
  jg is_prime
  mov rax, r8
  xor edx, edx
  div r9                         ; n is positive: the unsigned division is right
  test rdx, rdx
  jz not_prime
  lea rcx, [r9 + 2]
  mov rax, r8
  xor edx, edx
  div rcx
  test rdx, rdx
  jz not_prime
  add r9, 6
  jmp next_i
is_prime:
  mov eax, 1
  ret
not_prime:
  xor eax, eax
  ret
;;; rt_upper_str
;;; (version 7.5) the unary operator +s for a str: ASCII letters a-z become A-Z, every other byte is copied as it is.
;;;   in: rsi = source bytes, rdi = destination bytes, rcx = number of bytes (may be 0)   out: nothing (the callers allocate the destination)
  test rcx, rcx
  jz str_done
str_next:
  movzx eax, byte ptr [rsi]
  lea edx, [rax - 97]
  cmp edx, 25
  ja str_store
  sub eax, 32
str_store:
  mov byte ptr [rdi], al
  inc rsi
  inc rdi
  dec rcx
  jnz str_next
str_done:
  ret
;;; rt_upper_text
;;; (version 7.5) the unary operator +t for a text: every code point of the table below becomes its upper-case form (one code point for one), the others are copied.
;;;   in: rsi = source code points (u32), rdi = destination (u32), rcx = number of code points (may be 0)   out: nothing
;;;   table: entries of four u32 (lo, hi, delta, step): a code point c with lo <= c <= hi and (c - lo) % step == 0 becomes c + delta (step is 1 or 2); lo = 0 ends it.
;;;   Covered: ASCII, Latin-1, Latin Extended-A (U+0100..017F), Greek (U+0386..03CE), Cyrillic (U+0400..052F). Not covered: other scripts, and the letters whose
;;;   upper case has several characters (the sharp s U+00DF stays as it is).
  lea rax, [rip + upper_table]
  mov r8, rax
  test rcx, rcx
  jz text_done
